LOCALE_BLOCKS = {
    "uz": "static const _uz = {",
    "uz_CYRL": "static const _uzCyrl = {",
    "ru": "static const _ru = {",
    "kk": "static const _kk = {",
    "ky": "static const _ky = {",
    "tr": "static const _tr = {",
}


def insert_keys_into_locale(content: str, locale: str, keys: dict[str, str]) -> str:
    marker = LOCALE_BLOCKS[locale]
    idx = content.find(marker)
    if idx == -1:
        raise RuntimeError(f"Locale block not found: {locale}")
    # insert before closing of block — find next locale block or `'en':`
    start = idx + len(marker)
    insertion = ""
    for key, value in keys.items():
        escaped = value.replace("\\", "\\\\").replace("'", "\\'")
        if f"'{key}':" in content:
            continue
        insertion += f"    '{key}': '{escaped}',\n"
    if not insertion:
        return content
    return content[:start] + "\n" + insertion + content[start:]


def add_getters(content: str) -> str:
    getter_block = """
  // ─── Orders & Customers ───
"""
    for key in ORDERS_KEYS:
        if f"String get {key}" in content:
            continue
        getter_block += f"  String get {key} => _t('{key}');\n"

    anchor = "  String get permManageSales => _t('permManageSales');"
    if anchor not in content:
        raise RuntimeError("permManageSales anchor not found")
    if "// ─── Orders & Customers ───" in content:
        return content
    return content.replace(anchor, anchor + getter_block)


def patch_en_dart(en_path: Path) -> None:
    text = en_path.read_text(encoding="utf-8")
    additions = ""
    for key, locales in ORDERS_KEYS.items():
        en_val = locales["en"].replace("\\", "\\\\").replace("'", "\\'")
        if f"'{key}':" in text:
            continue
        additions += f"  '{key}': '{en_val}',\n"
    if additions:
        text = text.replace(
            "const Map<String, String> kEnTranslations = {\n",
            "const Map<String, String> kEnTranslations = {\n" + additions,
        )
        en_path.write_text(text, encoding="utf-8")


def main() -> None:
    trans_path = ROOT / "lib/core/l10n/translations.dart"
    content = trans_path.read_text(encoding="utf-8")

    for locale in LOCALE_BLOCKS:
        locale_keys = {k: v[locale] for k, v in ORDERS_KEYS.items()}
        content = insert_keys_into_locale(content, locale, locale_keys)

    content = add_getters(content)
    trans_path.write_text(content, encoding="utf-8")

    patch_en_dart(ROOT / "lib/core/l10n/translations_en.dart")
    print(f"Added/verified {len(ORDERS_KEYS)} keys")


if __name__ == "__main__":
    main()
